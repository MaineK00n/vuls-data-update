const alreadyFixedCriterionSuffix = " was already fixed"

func hasAlreadyFixedCriterion(oc oval.Criteria) bool {
	for _, cn := range oc.Criterions {
		if strings.HasSuffix(cn.Comment, alreadyFixedCriterionSuffix) {
			return true
		}
	}
	for _, ca := range oc.Criterias {
		if hasAlreadyFixedCriterion(ca) {
			return true
		}
	}
	return false
}

